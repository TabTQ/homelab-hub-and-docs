export const CONSTELLATION_KEYS: readonly string[] = CONSTELLATIONS.map((c) => c.key);

const BY_KEY = new Map(CONSTELLATIONS.map((c) => [c.key, c]));

export function getConstellation(key: string): Constellation | undefined { return BY_KEY.get(key); }

/** Display name for a key. Unknown keys come back as they are. */
export function constellationLabel(key: string): string { return BY_KEY.get(key)?.name ?? key; }
