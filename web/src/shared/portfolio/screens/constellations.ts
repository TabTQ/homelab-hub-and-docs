// Catalogue of well known constellations, drawn as the usual stick figures.
// Stars are [x, y] in a unit box (y grows downwards, the longer side spans 0 to 1, so the shorter side keeps its true proportion).
// `segments` join star indexes. `primary` lists every star index from most to least important, so the most linked skills
// land on the brightest stars.

export interface Constellation {
  key: string;
  name: string;
  stars: [number, number][];
  segments: [number, number][];
  primary: number[];
}

type Pt = [number, number];
type Seg = [number, number];

/** Fit raw sketch coordinates into the unit box without changing their proportions. */
function def(key: string, name: string, raw: Pt[], segments: Seg[], primary: number[]): Constellation {
  const xs = raw.map((p) => p[0]), ys = raw.map((p) => p[1]);
  const minX = Math.min(...xs), minY = Math.min(...ys);
  const span = Math.max(Math.max(...xs) - minX, Math.max(...ys) - minY) || 1;
  const stars = raw.map(([x, y]) => [+((x - minX) / span).toFixed(4), +((y - minY) / span).toFixed(4)] as Pt);
  return { key, name, stars, segments, primary };
}

